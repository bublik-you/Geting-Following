export const minuteOfDay = (time: string) => {
  const [hours, minutes] = time.split(':').map(Number);
  return hours * 60 + minutes;
};
export const waitMinutes = ([, ordered, served]: Pair) =>
  minuteOfDay(served) - minuteOfDay(ordered);
export const meanWait = (venue: Venue) => {
  const orders = pairedOrders[venue];
  return orders.reduce((sum, pair) => sum + waitMinutes(pair), 0) / orders.length;
};
export const formatMean = (venue: Venue) =>
  meanWait(venue).toLocaleString('ru-RU', { maximumFractionDigits: 1 });

