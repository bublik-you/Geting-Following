const stages = ['Вход', 'Выбор', 'Заказ', 'Ожидание', 'Получение', 'Завершение'];
const journey = (rows: string[]) => stages.map((label, index) => ({ label, text: rows[index], critical: [1, 2, 4].includes(index) }));

const jobs = (entries: Record<string, string>, props: string[]) =>
  fields(entries).map((item, index) => ({ ...item, prop: props[index] }));

const observation = (title: string, kind: string, note: string, x: number, y: number, lines: string[] = []) =>
  ({ title, kind, note, point: { x, y }, lines });

const plan = (titles: string[], rows: string[][]) => titles.map((title, index) => ({
  title, period: ['0–12 ч', '12–24 ч', '24–48 ч'][index],
  fields: fields({ Задача: rows[index][0], Ответственный: rows[index][1], Ресурсы: rows[index][2], Проверка: rows[index][3] }),
}));

